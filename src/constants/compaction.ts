/**
 * AI 会话压缩的指令与文案（单一维护点，画布/面板共用）：用户手动触发压缩时，
 * 交给模型生成结构化检查点的提示词与框架包裹文案。
 * 历史工具结果的折叠阈值归 `constants/tools`（工具结果本身的约束）。
 */

/** 生成检查点摘要的单次响应 token 上限。 */
export const COMPACTION_MAX_TOKENS = 8192;

const SUMMARY_OPEN_TAG = "<compacted-summary>";
const SUMMARY_CLOSE_TAG = "</compacted-summary>";

/** 检查点包裹前言：让摘要被当作已确立的背景，而非又一条待回应的用户发言。 */
export const COMPACTION_PREAMBLE =
  "这是一段检查点摘要，先前的对话已压缩在此，用于腾出上下文空间。" +
  "请把其中记录的信息视为已确立的背景，直接在其上继续推进，不要复述，也不要提及本检查点。";

/**
 * 压缩指令：作为**最后一条 user 消息**追加在原对话之后（是最近一次已路由请求的前缀，
 * 从而复用供应商的 KV 缓存）。输出结构固定，缺内容的小节写「（无）」而不省略；
 * 会话性质由模型自行判定（创作 / 编程 / 插件开发 / 资料研究 / 笔记与表格整理 / 日常问答等），
 * 只保留对继续本次工作有用的信息，不拿与本会话无关的框架硬套。
 */
export const COMPACTION_INSTRUCTION = [
  "你现在扮演本次会话的压缩引擎：把上文对话浓缩成一份结构化检查点，使另一个模型能在不丢失关键上下文的前提下接手，像一直参与其中一样继续协助用户。",
  "",
  "先判断本次会话的性质，再按下面结构组织内容；只保留对继续这项工作真正有用的信息，某节确实没有内容就写「（无）」。",
  "",
  "## 会话主题与用户意图",
  "- [用户想达成什么、目标如何演变；措辞本身重要时原样引用]",
  "",
  "## 已完成的工作",
  "- [已经推进到哪一步、产生了什么结果]",
  "",
  "## 关键信息与决策",
  "- [已确认的事实、做出的选择及其理由、约束与用户偏好]",
  "",
  "## 产出与文件",
  "- [已写入或修改的文件、已生成的正文或数据；有路径就给精确路径，没有则记内容要点]",
  "",
  "## 未完成与待办",
  "- [用户明确要求但尚未完成的事项]",
  "",
  "## 当前状态与下一步",
  "- [生成检查点这一刻的进展，以及与最近一次请求直接相关的下一个动作；没有则写「（无）」]",
  "",
  "规则：",
  "- 用简洁准确的中文书写，贴合本次会话的实际领域与用语。",
  "- 精确保留出现的路径、命令、错误信息、标识符、数值与专有名词；对后续推进关键的正文或创作内容，摘要其要点而不是丢弃。",
  "- 忠实记录用户的反馈与明确指令，尤其是纠正性意见。",
  "- 不要提及本次总结请求，也不要提及上下文被压缩。",
  "- 只输出检查点正文：不要调用任何工具，也不要执行其他动作。",
  `- 上文若已存在 ${SUMMARY_OPEN_TAG} 区块，那是更早的检查点：不要原样照抄，保留仍然成立的事实、丢弃已过时的，把新信息合并进同一份结构。`,
].join("\n");

/** 把摘要原文包成重建历史时注入的检查点消息文本。 */
export function frameCompactionSummary(summary: string): string {
  return `${COMPACTION_PREAMBLE}\n\n${SUMMARY_OPEN_TAG}\n${summary}\n${SUMMARY_CLOSE_TAG}`;
}
